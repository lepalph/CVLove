/** Langue de l'interface au premier lancement : navigator.language, sinon anglais. */
export function detectLang(nav: string | undefined = typeof navigator === 'undefined' ? undefined : navigator.language): Lang {
  const code = (nav ?? 'en').slice(0, 2).toLowerCase()
  return (Object.keys(ui) as Lang[]).includes(code as Lang) ? (code as Lang) : 'en'
}
